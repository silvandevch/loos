#!/usr/bin/env python3
"""apiset.map -> apiset_table.c (sorted by byte order, duplicate-checked)."""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
rows = {}
for ln, line in enumerate(open(os.path.join(here, "apiset.map")), 1):
    line = line.split("#", 1)[0].strip()
    if not line: continue
    p = line.split()
    if len(p) != 2: sys.exit(f"apiset.map:{ln}: want 'contract host'")
    c, h = p[0].lower(), p[1].lower()
    if c in rows and rows[c] != h: sys.exit(f"apiset.map:{ln}: {c} maps to both {rows[c]} and {h}")
    rows[c] = h
with open(os.path.join(here, "apiset_table.c"), "w") as o:
    o.write("/* GENERATED by gen_table.py from apiset.map - do not edit. */\n#include \"apiset_table.h\"\n")
    o.write("const struct apiset_entry apiset_table[] = {\n")
    for c in sorted(rows): o.write(f'    {{ "{c}", "{rows[c]}" }},\n')
    o.write("};\nconst size_t apiset_table_len = sizeof apiset_table / sizeof apiset_table[0];\n")
print(len(rows), "contracts")
