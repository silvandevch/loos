#!/usr/bin/env python3
"""Generates src/ioctl_abi.rs from the Linux uapi headers (<linux/btrfs.h>, <linux/fs.h>, <linux/fiemap.h>).

The numbers and struct layouts are measured with the host C compiler, never typed by hand:
    python3 gen/gen_ioctl_abi.py > src/ioctl_abi.rs
The test `ioctl_abi_matches_kernel_headers` re-measures and fails if the checked-in file drifted.
"""
import re, subprocess, sys, tempfile, os

HDR = "/usr/include/linux/btrfs.h"
text = open(HDR).read()
noc = re.sub(r"/\*.*?\*/", "", text, flags=re.S)

ioctls = sorted(set(re.findall(r"#define\s+(BTRFS_IOC_\w+)\s", noc)))
ioctls += ["FICLONE", "FICLONERANGE", "FIDEDUPERANGE", "FS_IOC_GETFLAGS", "FS_IOC_SETFLAGS", "FS_IOC_FIEMAP", "FS_IOC_GETFSLABEL", "FS_IOC_SETFSLABEL"]
ioctls = sorted(set(ioctls))
# BTRFS_IOC_GET_FSLABEL aliases FS_IOC_GETFSLABEL etc.; keep both names

structs = {}
for m in re.finditer(r"struct\s+(btrfs_\w+)\s*\{(.*?)\n\}\s*(?:__attribute__\s*\(\([^)]*\)\)\s*)?;", noc, flags=re.S):
    name, body = m.group(1), m.group(2)
    body = re.sub(r"\b(?:union|struct)\s*\{", "{", body)          # anonymous aggregates: flatten
    body = body.replace("{", ";").replace("}", ";")
    fields = []
    for decl in body.split(";"):
        decl = decl.strip()
        if not decl or decl.startswith("#"):
            continue
        for part in decl.split(","):
            mm = re.search(r"([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*$", part.strip())
            if mm and mm.group(1) not in ("unsigned", "long", "char"):
                fields.append(mm.group(1))
    # drop type-only tokens produced by flattening (struct member types without a name)
    structs[name] = [f for i, f in enumerate(fields) if f not in structs and not f.startswith("btrfs_")]
extra = {"file_clone_range": ["src_fd", "src_offset", "src_length", "dest_offset"],
         "file_dedupe_range": ["src_offset", "src_length", "dest_count", "reserved1", "reserved2", "info"],
         "file_dedupe_range_info": ["dest_fd", "dest_offset", "bytes_deduped", "status", "reserved"],
         "fiemap": ["fm_start", "fm_length", "fm_flags", "fm_mapped_extents", "fm_extent_count", "fm_reserved", "fm_extents"],
         "fiemap_extent": ["fe_logical", "fe_physical", "fe_length", "fe_reserved64", "fe_flags", "fe_reserved"]}
structs.update(extra)

def build(structs):
    prog = ['#include <stdio.h>', '#include <stddef.h>', '#include <sys/ioctl.h>', '#include <linux/types.h>', '#include <linux/fs.h>', '#include <linux/fiemap.h>', '#include <linux/btrfs.h>', 'int main(void){']
    for n in ioctls:
        prog.append('printf("I %s %%lu\\n", (unsigned long)%s);' % (n, n))
    for s_, fs in sorted(structs.items()):
        prog.append('printf("S %s %%zu\\n", sizeof(struct %s));' % (s_, s_))
        for f in fs:
            prog.append('printf("F %s %s %%zu\\n", offsetof(struct %s, %s));' % (s_, f, s_, f))
    prog.append('return 0;}')
    return "\n".join(prog)

d = tempfile.mkdtemp()
c = os.path.join(d, "p.c")
for _ in range(40):
    open(c, "w").write(build(structs))
    r = subprocess.run(["gcc", "-w", "-o", os.path.join(d, "p"), c], capture_output=True, text=True, env=dict(os.environ, LC_ALL="C.UTF-8"))
    if r.returncode == 0:
        break
    bad = re.findall(r"struct (\w+)[\u2019'] has no member named [\u2018'](\w+)[\u2019']", r.stderr)
    if not bad:
        sys.stderr.write(r.stderr)
        sys.exit(1)
    for st, fld in bad:
        structs[st] = [f for f in structs[st] if f != fld]
else:
    sys.exit("could not converge")
out = subprocess.run([os.path.join(d, "p")], capture_output=True, text=True, check=True).stdout.splitlines()

def snake(s): return s.upper()
o = ["// @generated by gen/gen_ioctl_abi.py from the Linux uapi headers - do not edit.",
     "//! Measured ioctl numbers and struct layouts of the Linux btrfs ABI.", "", "/// `(name, ioctl number)` for every btrfs/VFS ioctl we implement or recognise.", "pub const IOCTLS: &[(&str, u32)] = &["]
cur = None
layout = {}
for line in out:
    p = line.split()
    if p[0] == "I":
        o.append('    ("%s", 0x%08x),' % (p[1], int(p[2])))
    elif p[0] == "S":
        layout[p[1]] = [int(p[2]), []]
    elif p[0] == "F":
        layout[p[1]][1].append((p[2], int(p[3])))
o.append("];\n")
o.append("/// Struct sizes and field offsets.\n#[allow(missing_docs)]\npub mod layout {")
for s, (size, fl) in sorted(layout.items()):
    o.append("    pub mod %s {" % s)
    o.append("        pub const SIZE_OF: usize = %d;" % size)
    for f, off in fl:
        o.append("        pub const %s: usize = %d;" % (f.upper(), off))
    o.append("    }")
o.append("}")
print("\n".join(o))
