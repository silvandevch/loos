#!/usr/bin/env python3
"""Convert the generated font outline tables (src/shell/font_data.c) to Rust.

The C tables are produced by scripts/gen_font_outline.py from Inter (SIL OFL 1.1);
this converter keeps the numbers byte-identical while emitting `#[repr(C)]`
`LoosGlyph`/`LoosFont` statics for crates/loos-shell.

usage: gen_font_data.py [font_data.c] [font_data.rs]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def numbers(block):
    block = re.sub(r"/\*.*?\*/", "", block, flags=re.S)
    return [int(v) for v in re.findall(r"-?\d+", block)]


def rust_array(ty, name, values, per_line=16):
    out = [f"static {name}: [{ty}; {len(values)}] = ["]
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    out.append("];")
    return out


def convert(src, dst):
    text = src.read_text()
    arrays = {}
    for ty, name, body in re.findall(
            r"static const (int16_t|uint8_t|uint16_t|loos_glyph)\s+(\w+)\[\]\s*=\s*\{(.*?)\};",
            text, flags=re.S):
        arrays[name] = (ty, body)

    out = [
        "// @generated by crates/loos-shell/tools/gen_font_data.py from src/shell/font_data.c.",
        "// Inter outlines (SIL OFL 1.1, see THIRD-PARTY.md), font units; do not edit.",
        "",
        "use crate::font::{Font, LoosFont, LoosGlyph};",
        "",
    ]
    fonts = []
    for face in ("regular", "semibold"):
        for kind, ty in (("pts", "i16"), ("on", "u8"), ("ends", "u16")):
            name = f"{face}_{kind}"
            _, body = arrays[name]
            out += rust_array(ty, name.upper(), numbers(body))
            out.append("")
        _, body = arrays[f"{face}_glyphs"]
        glyphs = re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", body)
        out.append(f"static {face.upper()}_GLYPHS: [LoosGlyph; {len(glyphs)}] = [")
        for cp, adv, pt0, end0, ncont in glyphs:
            out.append(f"    LoosGlyph {{ cp: {cp}, adv: {adv}, pt0: {pt0}, end0: {end0}, ncont: {ncont} }},")
        out.append("];")
        out.append("")
        fonts.append((face, len(glyphs)))

    for face, nglyphs in fonts:
        m = re.search(rf"const loos_font loos_font_{face}\s*=\s*\{{\s*(\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(\d+)", text)
        upm, ascent, descent, declared = (int(v) for v in m.groups())
        assert declared == nglyphs, (face, declared, nglyphs)
        up = face.upper()
        out += [
            f"/// C `loos_font_{face}`.",
            "#[no_mangle]",
            f"pub static loos_font_{face}: LoosFont = LoosFont {{",
            f"    upm: {upm}, ascent: {ascent}, descent: {descent}, nglyphs: {nglyphs},",
            f"    glyphs: {up}_GLYPHS.as_ptr(), pts: {up}_PTS.as_ptr(),",
            f"    on: {up}_ON.as_ptr(), ends: {up}_ENDS.as_ptr(),",
            "};",
            "",
            f"/// `loos_font_{face}` as a safe view over the static tables.",
            f"pub fn {face}() -> Font<'static> {{",
            f"    Font::new({upm}, {ascent}, {descent}, &{up}_GLYPHS, &{up}_PTS, &{up}_ON, &{up}_ENDS)",
            "}",
            "",
        ]
    dst.write_text("\n".join(out))
    print(f"wrote {dst.relative_to(ROOT)}: {len(fonts)} faces")


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src/shell/font_data.c"
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "crates/loos-shell/src/font_data.rs"
    convert(src, dst)


if __name__ == "__main__":
    main()
