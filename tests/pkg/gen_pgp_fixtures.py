#!/usr/bin/env python3
"""Generates tests/pkg/pgp_fixture.h with keys and signatures made by the host's GnuPG (the reference implementation):
 - key A: RSA-2048 primary that signs directly
 - key B: RSA-2048 certify-only primary + separate RSA-2048 signing subkey
 - key C: RSA-2048 that expires (we backdate checks against the expiry)
 - key D: ed25519 (must be reported unsupported, not crash)
plus InRelease (clearsigned, SHA256 and SHA512), Release + detached Release.gpg (binary and armored)."""
import os, subprocess, sys, tempfile, shutil

home = tempfile.mkdtemp(prefix="gnupg")
os.chmod(home, 0o700)
env = dict(os.environ, GNUPGHOME=home)
def gpg(*a, inp=None, out=False):
    r = subprocess.run(["gpg", "--batch", "--yes", "--pinentry-mode", "loopback", "--passphrase", "", *a], env=env, input=inp, capture_output=True)
    if r.returncode: sys.stderr.write(r.stderr.decode()); raise SystemExit("gpg failed: " + " ".join(a))
    return r.stdout
def fpr(uid):
    for l in gpg("--with-colons", "--list-keys", uid).decode().splitlines():
        if l.startswith("fpr:"): return l.split(":")[9]
release = b"Origin: LoOS Test\nSuite: stable\nCodename: stable\nDate: Tue, 14 Nov 2023 22:13:20 UTC\nArchitectures: amd64\nComponents: main\nSHA256:\n e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855 0 main/binary-amd64/Packages\n"
open(os.path.join(home, "Release"), "wb").write(release)
rel = os.path.join(home, "Release")
gpg("--quick-gen-key", "Key A <a@loos.test>", "rsa2048", "sign", "never")
gpg("--quick-gen-key", "Key B <b@loos.test>", "rsa2048", "cert", "never")
gpg("--quick-add-key", fpr("Key B"), "rsa2048", "sign", "never")
gpg("--quick-gen-key", "Key C <c@loos.test>", "rsa2048", "sign", "1y")
gpg("--quick-gen-key", "Key D <d@loos.test>", "ed25519", "sign", "never")
out = {}
for k in "ABCD":
    out["KEY_" + k] = gpg("--armor", "--export", "Key %s" % k).decode()
    out["FPR_" + k] = fpr("Key %s" % k)
def sign(user, mode, digest, armor):
    args = ["-u", "Key %s" % user, "--digest-algo", digest]
    if armor: args.append("--armor")
    return gpg(*args, mode, "-o", "-", rel)
out["INRELEASE_A_SHA256"] = sign("A", "--clearsign", "SHA256", False).decode()
out["INRELEASE_A_SHA512"] = sign("A", "--clearsign", "SHA512", False).decode()
out["INRELEASE_B_SHA256"] = sign("B", "--clearsign", "SHA256", False).decode()
out["INRELEASE_C_SHA256"] = sign("C", "--clearsign", "SHA256", False).decode()
out["INRELEASE_D"] = sign("D", "--clearsign", "SHA256", False).decode()
out["INRELEASE_A_SHA1"] = sign("A", "--clearsign", "SHA1", False).decode()
out["RELEASE"] = release.decode()
out["RELEASE_GPG_A_ARMOR"] = sign("A", "--detach-sign", "SHA256", True).decode()
bin_sig = sign("A", "--detach-sign", "SHA512", False)
out["RELEASE_GPG_A_BIN_HEX"] = bin_sig.hex()
with open(sys.argv[1] if len(sys.argv) > 1 else "tests/pkg/pgp_fixture.h", "w") as f:
    f.write("/* generated by tests/pkg/gen_pgp_fixtures.py from the host GnuPG; do not edit */\n")
    for k, v in out.items():
        if k.endswith("_HEX"):
            b = bytes.fromhex(v)
            f.write("static const unsigned char %s[] = {%s};\n" % (k[:-4] + "_BYTES", ",".join(str(x) for x in b)))
        else:
            lines = v.split("\n")
            f.write("static const char %s[] =\n" % k)
            f.write("\n".join('    "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in lines[:-1] if True) or '    ""')
            f.write(";\n")
shutil.rmtree(home, ignore_errors=True)
print("ok", len(out))
