#!/usr/bin/env python3
"""Report API-set hosts without a corresponding LoOS Win32 source module."""

import argparse
from collections import Counter
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[3]
MAP = ROOT / "src/win32/apisets/apiset.map"
REPORT = ROOT / "tests/win32/apisets/host-coverage.md"
SOURCE_SUFFIXES = {".c", ".cc", ".cpp"}


def read_hosts(path: Path) -> Counter[str]:
    counts: Counter[str] = Counter()
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        fields = line.split("#", 1)[0].split()
        if not fields:
            continue
        if len(fields) != 2:
            raise ValueError(f"{path}:{line_number}: expected contract and host")
        contract, host = fields
        if not host.lower().endswith(".dll"):
            raise ValueError(f"{path}:{line_number}: host must end in .dll")
        counts[host.lower()] += 1
    return counts


def module_source(root: Path, host: str) -> str | None:
    stem = host[:-4]
    module_dir = root / "src/win32" / stem
    if module_dir.is_dir() and any(
        source.is_file() and source.suffix.lower() in SOURCE_SUFFIXES
        for source in module_dir.rglob("*")
    ):
        return f"src/win32/{stem}/"
    module_file = root / "src/win32" / f"{stem}.c"
    if module_file.is_file():
        return f"src/win32/{stem}.c"
    return None


def render(root: Path) -> str:
    counts = read_hosts(root / MAP.relative_to(ROOT))
    rows = [(host, counts[host], module_source(root, host)) for host in sorted(counts)]
    missing = [(host, count) for host, count, source in rows if source is None]
    contracts_missing = sum(count for _, count in missing)

    lines = [
        "# API-set host coverage",
        "",
        "Generated by `python3 tests/win32/apisets/host_coverage.py --write`.",
        "An implemented host has C or C++ source under `src/win32/<host-stem>/`",
        "or in `src/win32/<host-stem>.c`. This source-level check does not claim",
        "that the module is complete or loadable.",
        "",
        f"- Hosts in schema: {len(rows)}",
        f"- Hosts with a source module: {len(rows) - len(missing)}",
        f"- Hosts without a source module: {len(missing)}",
        f"- Contracts routed to missing hosts: {contracts_missing}",
        "",
        "| Host DLL | Contracts | Coverage | Source |",
        "|---|---:|---|---|",
    ]
    for host, count, source in rows:
        coverage = "implemented" if source else "missing"
        lines.append(f"| `{host}` | {count} | {coverage} | {f'`{source}`' if source else '—'} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help=f"write {REPORT.relative_to(ROOT)}")
    mode.add_argument("--check", action="store_true", help="fail if the saved report is stale")
    args = parser.parse_args()
    output = render(ROOT)

    if args.write:
        REPORT.write_text(output, encoding="utf-8")
        print(f"wrote {REPORT.relative_to(ROOT)}")
    elif args.check:
        if not REPORT.exists() or REPORT.read_text(encoding="utf-8") != output:
            print(f"{REPORT.relative_to(ROOT)} is stale; regenerate it with --write", file=sys.stderr)
            return 1
        print(f"{REPORT.relative_to(ROOT)} is current")
    else:
        sys.stdout.write(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
