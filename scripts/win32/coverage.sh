#!/usr/bin/env bash
# Regenerate docs/COVERAGE-win32.md: how much of real Windows binaries' import surface LoOS provides.
#   scripts/win32/coverage.sh [target-dir-with-PEs...]
# Default targets: Wine's builtin PE tools and the C runtime DLLs, when installed (they are ordinary
# Windows binaries that exercise the Win32 API the way real programs do). Read-only analysis.
set -euo pipefail
here="$(cd "$(dirname "$0")/../.." && pwd)"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
"$here/scripts/win32/build-pe.sh" "$tmp/pe" >/dev/null
S="$here/src/win32"
clang -std=gnu11 -O1 -I"$S/pe" -I"$S/apisets" "$here/tools/win32/importgap.c" "$S/pe/pe.c" "$S/apisets/apiset.c" "$S/apisets/apiset_table.c" -o "$tmp/importgap"
targets=()
if [ $# -gt 0 ]; then for d in "$@"; do targets+=( "$d"/*.exe "$d"/*.dll ); done
else
    for d in /usr/lib64/wine*/wine/x86_64-windows; do
        targets+=( "$d"/*.exe "$d"/ucrtbase.dll "$d"/msvcrt.dll "$d"/vcruntime140.dll ); done
fi
[ ${#targets[@]} -gt 0 ] || { echo "no targets found" >&2; exit 1; }
"$tmp/importgap" "$tmp/pe" "${targets[@]}" > "$tmp/gap.md"
python3 - "$tmp/gap.md" > "$here/docs/COVERAGE-win32.md" <<'PY'
import re, sys, collections
t = open(sys.argv[1]).read()
miss = collections.Counter(); nomod = collections.Counter(); tot = ok = 0; n = 0
for sec in t.split('\n## ')[1:]:
    n += 1
    m = re.search(r'imports: (\d+), satisfied by LoOS modules: (\d+)', sec)
    if m: tot += int(m.group(1)); ok += int(m.group(2))
    m = re.search(r'\*\*missing from shipped modules:\*\*(.*)', sec)
    if m:
        for s in re.findall(r'`([^`]+)`', m.group(1)): miss[s.lower()] += 1
    m = re.search(r'\*\*modules not shipped \(symbols\):\*\*(.*)', sec)
    if m:
        for mod, c in re.findall(r'(\S+)\((\d+)\)', m.group(1)): nomod[mod.lower()] += int(c)
print('# Win32 coverage (generated)\n')
print('Generated by `scripts/win32/coverage.sh`. Targets are ordinary Windows binaries (see the script).')
print('A symbol counts as satisfied when a LoOS DLL exports it (API sets resolved first, forwarders count).\n')
print(f'- targets analysed: {n}\n- total imports: {tot}, satisfied by shipped modules: {ok} ({100*ok//max(tot,1)}%)\n')
print('## Most-wanted missing exports in modules LoOS ships (by number of targets importing them)\n')
print('| count | symbol |\n|---|---|')
for s, c in miss.most_common(60): print(f'| {c} | `{s}` |')
print('\n## Modules LoOS does not ship yet (imported symbols across all targets)\n')
print('| symbols | module |\n|---|---|')
for m, c in nomod.most_common(25): print(f'| {c} | `{m}` |')
PY
head -22 "$here/docs/COVERAGE-win32.md"
