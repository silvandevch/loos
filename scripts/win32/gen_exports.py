#!/usr/bin/env python3
"""Generate linker inputs for the LoOS system DLLs.

  gen_exports.py def [--forward-to=MOD] <dll> <outdir> <src>...  -> <outdir>/<dll>.def
        exports = functions *defined* with WINAPI/NTAPI; with --forward-to every export is a forwarder to MOD
  gen_exports.py syscalls <tbl> <outc>              -> syscall stub translation unit
  gen_exports.py syscall-names <tbl>                -> one name per line

Exports come from definitions, never from headers, so a symbol is exported only if it is implemented.
"""
import re, sys, os

DEF = re.compile(r'^[A-Za-z_][\w \t\*]*?\b(?:WINAPI|NTAPI)\s+(\w+)\s*\(', re.M)

def exports_from(sources):
    names = set()
    for p in sources:
        text = open(p).read()
        text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
        for m in DEF.finditer(text):
            line_start = text.rfind('\n', 0, m.start()) + 1
            names.add(m.group(1))
    return sorted(names)

def read_tbl(path):
    rows = []
    for ln, line in enumerate(open(path), 1):
        line = line.split('#', 1)[0].strip()
        if not line: continue
        parts = line.split()
        if len(parts) != 2: sys.exit(f'{path}:{ln}: want "Name number"')
        rows.append((parts[0], int(parts[1], 0)))
    nums = [n for _, n in rows]
    if len(set(nums)) != len(nums): sys.exit(f'{path}: duplicate syscall numbers')
    if len({n for n, _ in rows}) != len(rows): sys.exit(f'{path}: duplicate names')
    return rows

if __name__ == '__main__':
    mode = sys.argv[1]
    if mode == 'def':
        args = sys.argv[2:]
        forward = None
        if args and args[0].startswith('--forward-to='):
            forward = args.pop(0).split('=', 1)[1]
        dll, outdir, srcs = args[0], args[1], args[2:]
        names = exports_from(srcs)
        extra = []
        for s in srcs:
            if s.endswith('.tbl'):
                extra += [n for n, _ in read_tbl(s)]
        srcs = [s for s in srcs if not s.endswith('.tbl')]
        names = sorted(set(exports_from(srcs)) | set(extra))
        os.makedirs(outdir, exist_ok=True)
        with open(os.path.join(outdir, dll + '.def'), 'w') as f:
            f.write(f'LIBRARY {dll}.dll\nEXPORTS\n')
            for n in names:
                f.write(f'    {n} = {forward}.{n}\n' if forward else f'    {n}\n')
        print(f'{dll}: {len(names)} exports')
    elif mode == 'syscalls':
        rows = read_tbl(sys.argv[2])
        with open(sys.argv[3], 'w') as f:
            f.write('/* GENERATED by scripts/win32/gen_exports.py from syscalls.tbl - do not edit. */\n')
            f.write('/* x64 syscall convention: r10 = rcx, eax = number, syscall. */\n')
            for name, num in rows:
                f.write(f'__asm__(".text\\n.globl {name}\\n{name}:\\n\\tmovq %rcx, %r10\\n\\tmovl ${num}, %eax\\n\\tsyscall\\n\\tret\\n");\n')
    elif mode == 'syscall-names':
        for n, _ in read_tbl(sys.argv[2]): print(n)
