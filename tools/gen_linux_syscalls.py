#!/usr/bin/env python3
"""Generate the Linux syscall diagnostic table used by loos-lin."""

from pathlib import Path
import sys


def load(path: Path) -> list[tuple[int, str]]:
    rows: list[tuple[int, str]] = []
    seen: set[int] = set()
    for line_no, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        fields = line.split()
        if len(fields) != 2 or not fields[0].isdigit() or not fields[1].replace("_", "").isalnum():
            raise SystemExit(f"{path}:{line_no}: expected '<number> <name>'")
        number = int(fields[0])
        if number < 0 or number > 1023:
            raise SystemExit(f"{path}:{line_no}: syscall number outside x86-64 range")
        if number in seen:
            raise SystemExit(f"{path}:{line_no}: duplicate syscall number {number}")
        seen.add(number)
        rows.append((number, fields[1]))
    rows.sort()
    return rows


def render(rows: list[tuple[int, str]]) -> str:
    lines = [
        "// @generated by tools/gen_linux_syscalls.py; do not edit.",
        "/// Linux x86-64 syscall number to diagnostic name.",
        "pub fn syscall_name(nr: u64) -> &'static str {",
        "    match nr {",
    ]
    lines.extend(f'        {number} => "{name}",' for number, name in rows)
    lines.extend([
        "        n if (BRIDGE_BASE..BRIDGE_BASE + 0x1_0000).contains(&n) => \"looswin\",",
        '        _ => "?",',
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    source = root / "tools" / "linux_syscalls.tab"
    output = root / "crates" / "loos-lin" / "src" / "syscalls_generated.rs"
    output.write_text(render(load(source)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
